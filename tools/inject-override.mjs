#!/usr/bin/env node
/**
 * Route-B override — architecture aware.
 *
 * Upstream has two entitlement architectures, so this tool has two modes:
 *
 *   mode=hook     0.27.x and older: plan/quota is orchestrated in TypeScript.
 *                 Inject the wrapper into native.ts (anchor based, survives
 *                 unrelated upstream churn).
 *   mode=license  canary / >=0.28: plan/quota is resolved inside the Rust
 *                 runtime (BackendRuntimeProvider.getWorkspaceQuotaStateV1),
 *                 so a TS hook is dead code. Upstream instead exposes an
 *                 official offline issuer -- issueLicenseV1({privateKey}) --
 *                 which means: bake YOUR public key at build time and install a
 *                 license you issued yourself. No code change at all.
 *
 * Usage:
 *   node tools/inject-override.mjs [--mode=auto|hook|license|off]
 *
 * Prints the resolved mode as the last line: `override-mode=<mode>`.
 * Exit: 0 ok / 2 hook anchor missing / 3 requested mode incompatible with tree.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const NATIVE = 'packages/backend/server/src/native.ts';
const CRYPTO = 'packages/backend/server/src/base/helpers/crypto.ts';
const BEGIN = '// >>> fork-ci:selfhost-override (generated by tools/inject-override.mjs) >>>';
const END = '// <<< fork-ci:selfhost-override <<<';

const arg = process.argv.find(a => a.startsWith('--mode='));
const MODE = (arg ? arg.split('=')[1] : 'auto').toLowerCase();

// --------------------------------------------------------------------- probe
function probe() {
  const notes = [];
  const quotaState = 'packages/backend/server/src/core/quota/state.ts';
  const entitlement = 'packages/backend/server/src/core/entitlement/service.ts';

  const hasQuotaState = existsSync(quotaState);
  let runtimeDriven = false;
  if (existsSync(entitlement)) {
    const ent = readFileSync(entitlement, 'utf8');
    runtimeDriven = /BackendRuntimeProvider/.test(ent) && !/builtinFree/.test(ent);
  }
  notes.push(`core/quota/state.ts: ${hasQuotaState ? 'present' : 'missing'}`);
  notes.push(
    `core/entitlement/service.ts: ${runtimeDriven ? 'delegates to the native runtime' : 'TS-side resolution'}`
  );

  const arch = hasQuotaState && !runtimeDriven ? 'ts' : 'runtime';
  return { arch, notes };
}

function conclude(mode, lines = []) {
  for (const l of lines) console.log(`  ${l}`);
  console.log(`override-mode=${mode}`);
}

function licenseChecklist() {
  return [
    'license mode: no code change is required on this revision.',
    'Upstream keeps the signed-license verifier and ships an offline issuer',
    '(native issueLicenseV1 takes the private key from the caller).',
    '',
    'Build requirements (all jobs, this is what the CI already passes through):',
    '  AFFINE_PRO_PUBLIC_KEY      <- your P-256 public key PEM, baked into the binding',
    '  AFFINE_PRO_LICENSE_AES_KEY <- only relevant on 0.27.x, ignored here',
    '',
    'Then, once the instance runs:',
    '  1. node tools/issue-license.mjs --workspace <WS_ID> --seats 100000 \\',
    '       --private-key <your private key PEM> --binding <path to @affine/server-native>',
    '  2. install the produced *.license (admin UI or installLicense GraphQL mutation)',
  ];
}

const { arch, notes } = probe();

if (MODE === 'off') {
  conclude('off', [`override disabled on request`, ...notes]);
  process.exit(0);
}

if (MODE === 'license' || (MODE === 'auto' && arch === 'runtime')) {
  if (MODE === 'license' && arch === 'ts') {
    console.log('  note: this tree still orchestrates entitlement in TypeScript;');
    console.log('        license mode works anyway (build with keys + install a license),');
    console.log('        but hook mode needs no keys at all.');
  }
  conclude('license', [`architecture: ${arch} (${notes.join(' | ')})`, '', ...licenseChecklist()]);
  process.exit(0);
}

if (arch === 'runtime' && MODE === 'hook') {
  console.log('  injector         FAILED (exit 3)');
  console.log('  hook mode is not available on this tree: entitlement resolution lives in the');
  console.log('  native runtime, so a TypeScript hook cannot influence plan/quota.');
  console.log(`  tree facts: ${notes.join(' | ')}`);
  console.log('  use --mode=license (bake your key pair + install a license you issued), or build');
  console.log('  from a revision that still orchestrates entitlement in TypeScript (0.27.x).');
  process.exit(3);
}

// ------------------------------------------------------------ mode=hook path
if (!existsSync(NATIVE)) {
  console.log(`  injector         FAILED (exit 2): ${NATIVE} not found -- run from the repository root.`);
  process.exit(2);
}

const src = readFileSync(NATIVE, 'utf8');
if (src.includes(BEGIN)) {
  conclude('hook', ['injector         already applied (sentinel found)', ...notes]);
  process.exit(0);
}

const ANCHOR =
  /^export const resolveEntitlementV1\s*=\s*\([\s\S]*?\)\s*:\s*ResolvedEntitlement\s*=>\s*serverNativeModule\.resolveEntitlementV1\([^;]*\);/m;
const match = src.match(ANCHOR);
if (!match) {
  console.log('  injector         FAILED (exit 2)');
  console.log(
    `  anchor "export const resolveEntitlementV1 = (...) => serverNativeModule.resolveEntitlementV1(...)" not found in ${NATIVE}.`
  );
  console.log('  the file exists but no longer contains that export -- re-target the override by hand');
  console.log('  or run with --mode=license if this revision resolves entitlements in the runtime.');
  process.exit(2);
}

const BLOCK = `${BEGIN}
// Route B (0.27.x): keep the native verifier intact -- it is still the only place
// that turns a plan into a quota -- but take the ceiling of the catalog for every
// target instead of letting self-hosted fall back to \`selfhost_free\`.
//
// Runtime switches (no rebuild needed):
//   SELFHOST_ENTITLEMENT_OVERRIDE=false   -> upstream behaviour
//   SELFHOST_OVERRIDE_SEATS=1..100000     -> seat count (default 100000)
export const SELFHOST_ENTITLEMENT_OVERRIDE =
  process.env.SELFHOST_ENTITLEMENT_OVERRIDE !== 'false';
export const SELFHOST_OVERRIDE_SEATS = (() => {
  const seat = Number(process.env.SELFHOST_OVERRIDE_SEATS ?? 100000);
  return Number.isInteger(seat) && seat >= 1 && seat <= 100000 ? seat : 100000;
})();
export const SELFHOST_OVERRIDE_PLAN = 'selfhost_team';

const forkIsSelfhosted = (): boolean => {
  if (typeof env !== 'undefined' && env) return env.selfhosted;
  const deployment =
    process.env.DEPLOYMENT_TYPE ??
    (process.env.NODE_ENV === 'development' ? 'affine' : 'selfhosted');
  return deployment === 'selfhosted';
};

export const resolveEntitlementV1 = (
  ...args: Parameters<typeof serverNativeModule.resolveEntitlementV1>
): ResolvedEntitlement => {
  if (!SELFHOST_ENTITLEMENT_OVERRIDE || !forkIsSelfhosted()) {
    return serverNativeModule.resolveEntitlementV1(...args);
  }

  // a genuine license payload still goes through the real verifier
  const input = args[0] as ResolveEntitlementInput | undefined;
  if (input?.signedPayload) {
    const real = serverNativeModule.resolveEntitlementV1(...args);
    if (real?.valid === true) {
      return real;
    }
  }

  // ask the native module for the sanctioned \`team\` catalog (legal on the
  // "cloud" deployment type), then relabel it as the self-hosted top plan
  const top = serverNativeModule.resolveEntitlementV1({
    ...(input as ResolveEntitlementInput),
    deploymentType: 'cloud',
    targetType: input?.targetType ?? 'workspace',
    plan: 'team',
    quantity: SELFHOST_OVERRIDE_SEATS,
    signedPayload: undefined,
    publicKey: undefined,
    licenseAesKey: undefined,
  });

  return {
    ...top,
    plan: SELFHOST_OVERRIDE_PLAN,
    valid: true,
    status: 'active',
    flags: { ...(top?.flags ?? {}), unlimitedCopilot: true },
  };
};
${END}`;

writeFileSync(NATIVE, src.replace(ANCHOR, BLOCK));
console.log(
  `  injector         injected into ${NATIVE} (replaced ${match[0].split('\n').length} line(s) with ${BLOCK.split('\n').length})`
);

// ------------------------------------------- advisory: 0.27.x key override
if (existsSync(CRYPTO)) {
  const crypto = readFileSync(CRYPTO, 'utf8');
  if (crypto.includes('AFFINE_SELFHOST_LICENSE_KEY_OVERRIDE')) {
    console.log('  injector         crypto.ts already patched');
  } else {
    const pubAnchor = /(\n\s*private loadAFFiNEProPublicKey\(\)\s*\{\n)/;
    const aesAnchor = /(\n\s*private loadAFFiNEProLicenseAESKey\(\)\s*\{\n)/;
    const pubInject =
      '    // route A: let an operator trust a self-issued key pair at runtime\n' +
      "    if (\n      process.env.AFFiNE_PRO_PUBLIC_KEY &&\n      process.env.AFFINE_SELFHOST_LICENSE_KEY_OVERRIDE !== '0'\n    ) {\n" +
      '      return Buffer.from(process.env.AFFiNE_PRO_PUBLIC_KEY);\n    }\n\n';
    const aesInject =
      '    // route A: same for the license AES key\n' +
      "    if (\n      process.env.AFFiNE_PRO_LICENSE_AES_KEY &&\n      process.env.AFFINE_SELFHOST_LICENSE_KEY_OVERRIDE !== '0'\n    ) {\n" +
      '      return this.sha256(process.env.AFFiNE_PRO_LICENSE_AES_KEY);\n    }\n\n';

    let out = crypto;
    let done = 0;
    if (pubAnchor.test(out)) {
      out = out.replace(pubAnchor, `$1${pubInject}`);
      done++;
    }
    if (aesAnchor.test(out)) {
      out = out.replace(aesAnchor, `$1${aesInject}`);
      done++;
    }
    if (done === 2) {
      writeFileSync(CRYPTO, out);
      console.log('  injector         crypto.ts runtime key override injected (route A, 0.27.x only)');
    } else {
      console.log(
        `  injector         note: crypto.ts anchors not found (${done}/2) -- route A needs a manual edit; route B unaffected`
      );
    }
  }
}

conclude('hook', notes);
